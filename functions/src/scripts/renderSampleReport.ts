// ============================================================================
// renderSampleReport - developer script: render a representative report PDF
// with NO emulator, network or credentials.
//
// The renderer (report/render.ts) is pure presentation: it takes a fully
// resolved ReportModel and returns PDF bytes. So this script builds a rich
// model BY HAND - shaped like the seed's demo world - and renders it, giving
// the team a real PDF to eyeball for layout regressions:
//   - 12 Section 2 subjects, including one observation LONGER THAN A PAGE
//     (exercising the row split + repeated Question/Answer header),
//   - photo/flag-composite placeholders (unavailable images render the honest
//     "image unavailable" box - no bytes needed),
//   - flagged locations on questions of several types: one plan, TWO plans, a
//     non-conformity that also carries its plans into the action plan, and a
//     flag whose composite could not be fetched. Real PNG bytes come from the
//     seed's dependency-free generator, so the plans are actually LOOKED at
//     rather than measured as empty boxes,
//   - a full severity-ordered action plan with a flag composite slot,
//   - org branding (name, brand colour; logo intentionally unavailable),
//   - 'Page N of M' footers via the buffered final pass.
//
// Run (from functions/):  npm run render:sample  [-- /path/to/out.pdf]
// Default output: ./sample-report.pdf (the functions/ directory).
// ============================================================================

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { renderReportPdf } from '../report/render';
import type {
  ReportAction,
  ReportModel,
  ReportSection,
  ResolvedImage,
} from '../report/assemble';
import type {
  MatrixAnswer,
  QuestionMatrix,
  ReportStandard,
} from '../shared/types';
import { REPORT_STANDARDS } from '../shared/types';
import { flagComposite } from '../seed/png';

/** An intentionally-unavailable image: the renderer paints its titled
 *  "image unavailable" placeholder box, so no bytes are required. */
function placeholder(title: string): ResolvedImage {
  return { title, available: false };
}

/**
 * A REAL flag composite - a floor plan flattened with severity pins, exactly what
 * the app uploads on save and what assemble.ts downloads. Generated by the seed's
 * dependency-free PNG encoder so the sample exercises the drawn image path (box
 * height, caption placement, page fit) rather than the placeholder path.
 *
 * `title` is composed the way assemble.ts composes it, so the captions in the
 * sample read exactly as a released report's do.
 */
function flagLocation(
  prefix: string,
  planName: string | undefined,
  index: number,
  total: number,
  pins: Array<{ x: number; y: number; severity: 'H' | 'M' | 'L' }>,
): ResolvedImage {
  const position = total > 1 ? ` (${index + 1} of ${total})` : '';
  return {
    title: planName ? `${prefix}: ${planName}${position}` : `${prefix}${position}`,
    data: flagComposite(640, 480, pins),
    available: true,
  };
}

/** The two-plan finding in subject 2.1, shared by its Section 2 row and by the
 *  action it was released as - the same composites, captioned identically, so
 *  the deliberate repetition between the two sections can be seen side by side. */
function escapeRouteFlags(prefix: string): ResolvedImage[] {
  return [
    flagLocation(prefix, 'Ground floor plan', 0, 2, [
      { x: 0.28, y: 0.42, severity: 'H' },
      { x: 0.62, y: 0.35, severity: 'H' },
    ]),
    flagLocation(prefix, 'First floor plan', 1, 2, [
      { x: 0.45, y: 0.68, severity: 'H' },
    ]),
  ];
}

/** Deterministic filler prose (no lorem-ipsum dependency). */
function prose(sentences: number): string {
  const bank = [
    'The escape route was found to be partially obstructed by stored materials at the time of inspection.',
    'Compartmentation between the riser cupboard and the adjoining corridor requires attention.',
    'The self-closing device did not bring the door fully to the rebate from the standing-open position.',
    'Signage along the corridor was legible and correctly directional throughout.',
    'Emergency lighting operated on test at each of the sampled call points.',
    'The responsible person should ensure records of weekly alarm tests are maintained in the log book.',
    'Combustible storage should be relocated away from the electrical intake cupboard as a priority.',
    'The dry riser inlet cabinet was secure and its signage compliant with the relevant standard.',
  ];
  const out: string[] = [];
  for (let i = 0; i < sentences; i += 1) {
    out.push(bank[i % bank.length]);
  }
  return out.join(' ');
}

/** The BS 9792 style simple risk level estimator, used as the `matrix` question
 *  fixture so the drawn grid, its marked cell and its definitions can be eyeballed. */
const RISK_ESTIMATOR: QuestionMatrix = {
  rowLabel: 'Likelihood of fire',
  columnLabel: 'Potential consequences of fire',
  rows: ['Low', 'Medium', 'High'],
  columns: ['Slight harm', 'Moderate harm', 'Extreme harm'],
  cells: [
    ['Trivial risk', 'Tolerable risk', 'Moderate risk'],
    ['Tolerable risk', 'Moderate risk', 'Substantial risk'],
    ['Moderate risk', 'Substantial risk', 'Intolerable risk'],
  ],
  definitions: {
    Low: 'Fire is unlikely to occur given the ignition sources and controls observed.',
    Medium: 'Fire is reasonably foreseeable over the life of the premises.',
    High: 'Fire is likely to occur unless the arrangements are improved.',
    'Slight harm': 'Outbreak of fire is unlikely to result in serious injury.',
    'Moderate harm':
      'Outbreak of fire could result in injury, including serious injury, of one or more occupants.',
    'Extreme harm': 'Outbreak of fire could result in death of one or more occupants.',
  },
};

/**
 * The estimator row for a subject. Every subject carries one so the grid is
 * exercised at many different page positions in a single render, which is how a
 * grid that splits across a page break shows up. The chosen cell walks the grid
 * so the marker is seen in several positions; definitions are attached to the
 * first subject only, since twelve copies would pad the document without testing
 * anything new.
 */
function matrixRow(index: number): ReportSection['rows'][number] {
  const rowIndex = index % RISK_ESTIMATOR.rows.length;
  const columnIndex = (index * 2) % RISK_ESTIMATOR.columns.length;
  const answer: MatrixAnswer = {
    row: RISK_ESTIMATOR.rows[rowIndex],
    column: RISK_ESTIMATOR.columns[columnIndex],
    outcome: RISK_ESTIMATOR.cells[rowIndex][columnIndex],
  };
  const withoutDefinitions: QuestionMatrix = {
    rowLabel: RISK_ESTIMATOR.rowLabel,
    columnLabel: RISK_ESTIMATOR.columnLabel,
    rows: RISK_ESTIMATOR.rows,
    columns: RISK_ESTIMATOR.columns,
    cells: RISK_ESTIMATOR.cells,
  };
  return {
    questionText: 'Simple risk level estimator for this subject',
    // Mirrors the sentence assemble.ts builds for a matrix answer.
    answerText: `${answer.outcome} (${RISK_ESTIMATOR.rowLabel}: ${answer.row}; ${RISK_ESTIMATOR.columnLabel}: ${answer.column})`,
    questionType: 'matrix',
    guidance:
      'Cross the likelihood of fire with the potential consequences and record the cell that results.',
    matrix: index === 0 ? RISK_ESTIMATOR : withoutDefinitions,
    matrixAnswer: answer,
  };
}

/** 12 subjects, one carrying an observation well over a page of text. */
function buildSections(): ReportSection[] {
  const titles = [
    'Means of Escape',
    'Fire Doors',
    'Compartmentation',
    'Fire Detection and Alarm',
    'Emergency Lighting',
    'Signage and Notices',
    'Firefighting Equipment',
    'Electrical Hazards',
    'Housekeeping and Storage',
    'Arson Prevention',
    'External Wall Systems',
    'Management of Fire Safety',
  ];
  return titles.map((title, index) => {
    const code = `S${index + 1}`;
    const rows: ReportSection['rows'] = [
      {
        questionText: `Are the ${title.toLowerCase()} arrangements adequate for the building's use and occupancy profile?`,
        answerText: index % 3 === 0 ? 'No' : 'Yes',
        questionType: 'yesno',
        guidance:
          'Consider the building height, occupancy and the evacuation strategy in force.',
        ...(index % 3 === 0
          ? {
              observation:
                index === 3
                  ? // The page-splitting stress case: an observation far longer
                    // than one A4 page of small text (~120 sentences).
                    prose(120)
                  : prose(6),
              severity: (['H', 'M', 'L'] as const)[index % 3],
            }
          : {}),
        ...(index === 1
          ? {
              photos: [
                placeholder('Door to riser cupboard, third floor'),
                placeholder('Self-closer detail'),
                placeholder('Intumescent strip condition'),
              ],
            }
          : {}),
        // Subject 2.1 is the NON-CONFORMITY case: a finding pinned on two floor
        // plans. The same two composites are carried onto action 1 below, which
        // is where the deliberate repetition between Section 2 and the action
        // plan can be checked.
        ...(index === 0 ? { flagImages: escapeRouteFlags('Flagged location') } : {}),
        // Subject 2.6 is the case the report used to LOSE entirely: a location
        // pinned on a plain Yes/No question, which is not a finding, never became
        // an action, and so never reached the document.
        ...(index === 5
          ? {
              flagImages: [
                flagLocation('Flagged location', 'Second floor plan', 0, 1, [
                  { x: 0.34, y: 0.55, severity: 'L' },
                ]),
              ],
            }
          : {}),
      },
      {
        questionText: `Is documentation relating to ${title.toLowerCase()} available and current?`,
        answerText: 'Documentation reviewed on site; certificates current.',
        questionType: 'text',
        // A plan name long enough to overrun the caption box, so the clamp to two
        // lines (and the ellipsis on the second) is exercised rather than assumed.
        ...(index === 9
          ? {
              flagImages: [
                flagLocation(
                  'Flagged location',
                  'Basement car park and refuse store, north-east compartment',
                  0,
                  1,
                  [{ x: 0.5, y: 0.5, severity: 'L' }],
                ),
              ],
            }
          : {}),
      },
      {
        questionText: 'Overall condition assessment for this subject',
        answerText: index % 4 === 0 ? 'Requires improvement' : 'Satisfactory',
        questionType: 'select',
        options: ['Satisfactory', 'Requires improvement', 'Unsatisfactory'],
        ...(index % 4 === 0
          ? { observation: prose(4), severity: 'M' as const }
          : {}),
        // A recorded location whose composite could not be fetched. It is KEPT,
        // not dropped: the assessor flagged a location and the reader is told the
        // picture is missing rather than told nothing at all.
        ...(index === 7
          ? {
              flagImages: [
                {
                  title: 'Flagged location: Roof plant enclosure',
                  available: false,
                },
              ],
            }
          : {}),
      },
      matrixRow(index),
    ];
    return { code, title, rows };
  });
}

function buildActions(): ReportAction[] {
  const severities = ['H', 'H', 'M', 'M', 'M', 'L', 'L'] as const;
  return severities.map((severity, index) => ({
    severity,
    sectionCode: `S${(index % 12) + 1}`,
    question: `Are the arrangements adequate for the building's use? (finding ${index + 1})`,
    observation: prose(3 + (index % 4)),
    responsible: index % 2 === 0 ? 'Aisha Patel (Facilities)' : 'Managing agent',
    dueBy: Date.UTC(2026, 8 + (index % 3), 14),
    lifeProtection: index < 2,
    // The flag-location composites (legacy "Location" parity, 1057 AC2). Action 1
    // is the finding from subject 2.1 and carries BOTH of its plans, so the
    // multi-plan case is visible in the action plan as well as in Section 2;
    // action 3 keeps the unavailable case; the rest carry a single composite.
    flagImages:
      index === 0
        ? escapeRouteFlags('Location of finding')
        : index === 2
          ? [placeholder('Location of finding')]
          : [
              flagLocation(
                'Location of finding',
                `Floor ${1 + (index % 4)} plan`,
                0,
                1,
                [{ x: 0.3 + 0.1 * (index % 4), y: 0.4, severity }],
              ),
            ],
    images:
      index % 2 === 0
        ? [placeholder('Defect photograph'), placeholder('Wider context view')]
        : [],
  }));
}

