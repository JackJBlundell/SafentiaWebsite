/**
 * A stand-in accreditation certificate of `pages` pages, each stamped so its
 * position in the merged document is obvious at a glance.
 *
 * Generated rather than fixtured because the thing under test is the SPLICE and
 * the page numbering around it, not the artwork: a real certificate would make
 * the check no stronger and would put a third party's PDF in the repo.
 */
async function syntheticCertificate(pages: number): Promise<Buffer> {
  const { PDFDocument, StandardFonts } = await import('pdf-lib');
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.HelveticaBold);
  for (let i = 1; i <= pages; i += 1) {
    const page = doc.addPage([595.28, 841.89]);
    page.drawText(`CERTIFICATE PAGE ${i} OF ${pages}`, {
      x: 60,
      y: 700,
      size: 22,
      font,
    });
  }
  return Buffer.from(await doc.save());
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  // `--certificate=N` exercises the CERTIFICATED configuration: the renderer is
  // told how many pages will be spliced in behind the cover, then the splice
  // actually happens - the same two-step generateAndStore performs. Without
  // this the certificate path had no fixture at all, and the page numbering
  // around it (printed before the merge, verified after) could only be checked
  // by hand against a live release.
  const certificateArg = args.find((a) => a.startsWith('--certificate='));
  const certificatePages = certificateArg
    ? Math.max(0, Number.parseInt(certificateArg.split('=')[1] ?? '0', 10) || 0)
    : 0;
  // `--standard=pas79|bs9792|custom` selects the report PROFILE. The three
  // profiles share one engine and differ only in copy, but "differ only in copy"
  // is a claim worth being able to check by eye rather than by reading, so each
  // is renderable from the same fixture. Anything unrecognised falls back to
  // PAS 79, the dominant path.
  const standardArg = args.find((a) => a.startsWith('--standard='))?.split('=')[1];
  const standard: ReportStandard = REPORT_STANDARDS.includes(
    standardArg as ReportStandard,
  )
    ? (standardArg as ReportStandard)
    : 'pas79';
  const outPath = resolve(
    args.find((a) => !a.startsWith('--')) ?? './sample-report.pdf',
  );

  let pdf = await renderReportPdf(buildModel(standard), {
    insertedPagesAfterCover: certificatePages,
  });

  if (certificatePages > 0) {
    const { mergeCertificate } = await import('../report/certificate');
    const bytes = await syntheticCertificate(certificatePages);
    // The script's own quiet logger: the merge seam reports through one, and a
    // developer script has no structured-logging context to give it.
    pdf = await mergeCertificate(
      pdf,
      { bytes, pageCount: certificatePages },
      {
        info: () => {},
        warn: (message: string) => console.warn(message),
        error: (message: string) => console.error(message),
        debug: () => {},
      } as never,
    );
  }

  writeFileSync(outPath, pdf);
  console.log(`Sample report written: ${outPath} (${pdf.length} bytes)`);
  if (certificatePages > 0) {
    console.log(
      `Certificate: ${certificatePages} page(s) spliced in behind the cover. ` +
        'Check page 1 is the cover, the certificate follows it, and the first ' +
        `report page after it prints "Page | ${certificatePages + 2}".`,
    );
  }
  console.log(
    'Open it and check: Section 2 long-observation row splits across pages ' +
      'with the Question/Answer header repeated, and every footer reads "Page N of M". ' +
      'Flagged locations (subjects 2.1, 2.6, 2.8, 2.10 and every action card) must ' +
      'read as ruled rows of the table they sit in, each with its plan named beside ' +
      'it, and no page may OPEN with one - a plan is never separated from what it ' +
      'evidences.',
  );
}

void main().catch((error) => {
  console.error('renderSampleReport failed:', error);
  process.exit(1);
});
